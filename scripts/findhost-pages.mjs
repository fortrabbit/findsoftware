// Lists the filter pages a FindHost build has, so a record links only to pages that exist.
// Usage: node scripts/findhost-pages.mjs [path to a built FindHost dist/]
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { stringify } from 'yaml';

const dist = process.argv[2] ?? '../findhost/dist';
if (!existsSync(dist)) throw new Error(`No FindHost build at ${dist}: run pnpm build there first.`);

const pages = {};
for (const facet of ['runtimes', 'software', 'databases']) {
  pages[facet] = readdirSync(`${dist}/${facet}`, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}
writeFileSync(
  'src/data/findhost.yml',
  `# Generated by scripts/findhost-pages.mjs from a FindHost build: the filter pages it has.\n${stringify(pages, { flowLevel: 1 })}`,
);
console.log(
  Object.entries(pages)
    .map(([facet, values]) => `${values.length} ${facet}`)
    .join(', '),
);

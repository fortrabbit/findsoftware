// Lists the filter pages a FindHost build has, so a record links only to pages that exist,
// and the listed hosts a record page can name, with their own domain and FindHost page.
// Usage: node scripts/findhost-pages.mjs [path to a built FindHost dist/]
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { parse, stringify } from 'yaml';

const dist = process.argv[2] ?? '../findhost/dist';
if (!existsSync(dist)) throw new Error(`No FindHost build at ${dist}: run pnpm build there first.`);

const pages = {};
for (const facet of ['runtimes', 'software', 'databases']) {
  pages[facet] = readdirSync(`${dist}/${facet}`, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}
writeFileSync(
  'src/data/findhost.yml',
  `# Generated by scripts/findhost-pages.mjs from a FindHost build: the filter pages it has.\n${stringify(pages, { flowLevel: 1 })}`,
);
console.log(
  Object.entries(pages)
    .map(([facet, values]) => `${values.length} ${facet}`)
    .join(', '),
);

// providers.json holds only listed providers; the home URL and specialisation sit in the source files beside the build.
const { providers } = JSON.parse(readFileSync(`${dist}/providers.json`, 'utf8'));
const sources = `${dist}/../src/content/providers`;
const hosts = providers.map((provider) => {
  const front = parse(readFileSync(`${sources}/${provider.id}.md`, 'utf8').split(/^---$/m)[1]);
  return {
    id: provider.id,
    name: provider.name,
    url: front.urls?.home,
    path: provider.href,
    software: provider.facets.software ?? [],
    runtimes: provider.facets.runtimes ?? [],
    specialisation: front.specialisation ?? [],
  };
});
writeFileSync(
  'src/data/findhost-hosts.yml',
  `# Generated by scripts/findhost-pages.mjs from a FindHost build: the listed hosts.\n${stringify(hosts, { flowLevel: 2 })}`,
);
console.log(`${hosts.length} hosts`);
